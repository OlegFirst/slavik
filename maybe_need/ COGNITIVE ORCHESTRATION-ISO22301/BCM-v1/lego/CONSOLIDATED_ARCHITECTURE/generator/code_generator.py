    async def generate(self, architecture: Dict[str, Any]) -> Dict[str, str]:
        """Generate code based on architecture analysis with AI enhancement"""
        try:
            logger.info("🚀 Starting AI-enhanced code generation")

            # Try AI generation first if available
            if self.use_ai and self.ai_generator:
                try:
                    logger.info("🤖 Using AI code generation")
                    ai_generated_files = await self.ai_generator.generate_intelligent_code(architecture)

                    # Add AI explanation
                    explanation = await self.ai_generator.explain_architecture_decisions(architecture)
                    ai_generated_files["ARCHITECTURE_EXPLANATION.md"] = explanation

                    logger.info(f"✅ AI generated {len(ai_generated_files)} files")
                    return ai_generated_files

                except Exception as e:
                    logger.warning(f"AI generation failed, falling back to templates: {e}")
                    # Continue with template generation below

            # Fallback to template-based generation
            logger.info("📝 Using template-based generation")
            generated_files = {}
            pattern = architecture.get("primary_pattern", "monolith")

            if pattern == "monolith":
                files = self._generate_monolith(architecture)
            elif pattern == "microservices":
                files = self._generate_microservices(architecture)
            elif pattern == "serverless":
                files = self._generate_serverless(architecture)
            else:
                files = self._generate_hybrid(architecture)

            generated_files.update(files)

            # Generate common infrastructure files
            infrastructure_files = self._generate_infrastructure(architecture)
            generated_files.update(infrastructure_files)

            logger.info(f"✅ Template generated {len(generated_files)} files")
            return generated_files

        except Exception as e:
            logger.error(f"❌ Code generation failed: {e}")
            raise

