    def _render_template(self, template_name: str, variables: Dict[str, Any]) -> str:
        """Render a template with variables"""
        try:
            template_content = self.templates.get(template_name, "")
            if not template_content:
                logger.error(f"Template not found: {template_name}")
                return f"# Template rendering failed: Template '{template_name}' not found"
            env = Environment(loader=BaseLoader())
            template = env.from_string(template_content)
            return template.render(**variables)
        except Exception as e:
            logger.error(f"Template rendering failed: {e}")
            return f"# Template rendering failed: {e}"