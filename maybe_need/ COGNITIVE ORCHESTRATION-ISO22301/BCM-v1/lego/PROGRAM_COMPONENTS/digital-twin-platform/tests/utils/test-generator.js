/**
 * Автоматический генератор тестов для NASH 4.0 Digital Twin
 * Создает Jest тесты для всех модулей
 */

import fs from 'fs/promises';
import path from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);

class TestGenerator {
    constructor() {
        this.srcDir = path.join(__dirname, 'src');
        this.coreDir = path.join(__dirname, 'core');
        this.testsDir = path.join(__dirname, 'tests');
        this.modules = [];
    }

    /**
     * Сканирует все модули в проекте
     */
    async scanModules() {
        console.log('🔍 Сканирование модулей...');
        
        // Сканируем src/
        const srcFiles = await this.getJSFiles(this.srcDir);
        
        // Сканируем core/
        const coreFiles = await this.getJSFiles(this.coreDir);
        
        this.modules = [...srcFiles, ...coreFiles];
        console.log(`📁 Найдено ${this.modules.length} модулей`);
        
        return this.modules;
    }

    /**
     * Получает все JS файлы в директории
     */
    async getJSFiles(dir) {
        const files = [];
        
        try {
            const items = await fs.readdir(dir, { withFileTypes: true });
            
            for (const item of items) {
                const fullPath = path.join(dir, item.name);
                
                if (item.isDirectory()) {
                    // Рекурсивно обходим поддиректории
                    const subFiles = await this.getJSFiles(fullPath);
                    files.push(...subFiles);
                } else if (item.name.endsWith('.js') && !item.name.includes('test')) {
                    files.push(fullPath);
                }
            }
        } catch (error) {
            console.warn(`⚠️ Не удалось прочитать директорию ${dir}:`, error.message);
        }
        
        return files;
    }

    /**
     * Анализирует модуль и извлекает функции/классы
     */
    async analyzeModule(filePath) {
        try {
            const content = await fs.readFile(filePath, 'utf-8');
            
            // Находим экспортируемые классы
            const classes = this.extractClasses(content);
            
            // Находим экспортируемые функции
            const functions = this.extractFunctions(content);
            
            // Находим async функции
            const asyncFunctions = this.extractAsyncFunctions(content);
            
            return {
                filePath,
                relativePath: path.relative(__dirname, filePath),
                classes,
                functions,
                asyncFunctions,
                hasMockFunctions: this.hasMockFunctions(content)
            };
        } catch (error) {
            console.warn(`⚠️ Ошибка анализа ${filePath}:`, error.message);
            return null;
        }
    }

    /**
     * Извлекает классы из кода
     */
    extractClasses(content) {
        const classRegex = /(?:export\s+)?class\s+(\w+)/g;
        const classes = [];
        let match;
        
        while ((match = classRegex.exec(content)) !== null) {
            classes.push(match[1]);
        }
        
        return classes;
    }

    /**
     * Извлекает функции из кода
     */
    extractFunctions(content) {
        const functionRegex = /(?:export\s+)?(?:function\s+)?(\w+)\s*\([^)]*\)\s*\{/g;
        const functions = [];
        let match;
        
        while ((match = functionRegex.exec(content)) !== null) {
            if (!['if', 'while', 'for', 'switch', 'catch'].includes(match[1])) {
                functions.push(match[1]);
            }
        }
        
        return functions;
    }

    /**
     * Извлекает async функции
     */
    extractAsyncFunctions(content) {
        const asyncRegex = /async\s+(?:function\s+)?(\w+)\s*\(/g;
        const asyncFunctions = [];
        let match;
        
        while ((match = asyncRegex.exec(content)) !== null) {
            asyncFunctions.push(match[1]);
        }
        
        return asyncFunctions;
    }

    /**
     * Проверяет наличие mock функций
     */
    hasMockFunctions(content) {
        return /mock|stub|fake|demo/i.test(content);
    }

    /**
     * Генерирует Jest тест для модуля
     */
    generateTest(moduleInfo) {
        if (!moduleInfo) return null;

        const { relativePath, classes, functions, asyncFunctions, hasMockFunctions } = moduleInfo;
        const moduleName = path.basename(relativePath, '.js');
        const importPath = '../' + relativePath.replace(/\\/g, '/');

        let testContent = `/**
 * Автоматически сгенерированные тесты для ${moduleName}
 * Generated by NASH 4.0 Test Generator
 */

import { jest } from '@jest/globals';

`;

        // Импорты
        if (classes.length > 0) {
            testContent += `import { ${classes.join(', ')} } from '${importPath}';\n`;
        }

        if (functions.length > 0) {
            const standaloneImports = functions.filter(f => !classes.includes(f));
            if (standaloneImports.length > 0) {
                testContent += `import { ${standaloneImports.join(', ')} } from '${importPath}';\n`;
            }
        }

        testContent += '\n';

        // Mock предупреждение
        if (hasMockFunctions) {
            testContent += `// ⚠️ ВНИМАНИЕ: Модуль содержит mock/demo функции\n`;
            testContent += `// Убедитесь что они не используются в production\n\n`;
        }

        // Главный describe блок
        testContent += `describe('${moduleName}', () => {\n`;

        // Тесты для классов
        for (const className of classes) {
            testContent += this.generateClassTests(className);
        }

        // Тесты для standalone функций
        const standaloneFunc = functions.filter(f => !classes.includes(f));
        for (const funcName of standaloneFunc) {
            const isAsync = asyncFunctions.includes(funcName);
            testContent += this.generateFunctionTest(funcName, isAsync);
        }

        // Mock функции тесты
        if (hasMockFunctions) {
            testContent += `
    describe('Mock Functions Detection', () => {
        test('should identify mock functions in production code', () => {
            // ⚠️ КРИТИЧЕСКОЕ: Mock функции найдены в production коде
            console.warn('Mock functions detected in ${moduleName}');
            // TODO: Вынести mock функции в отдельные test-only модули
        });
    });
`;
        }

        testContent += '});\n';

        return testContent;
    }

    /**
     * Генерирует тесты для класса
     */
    generateClassTests(className) {
        return `
    describe('${className}', () => {
        let instance;

        beforeEach(() => {
            instance = new ${className}();
        });

        afterEach(() => {
            if (instance && typeof instance.cleanup === 'function') {
                instance.cleanup();
            }
            if (instance && typeof instance.shutdown === 'function') {
                instance.shutdown();
            }
        });

        test('should create instance', () => {
            expect(instance).toBeDefined();
            expect(instance).toBeInstanceOf(${className});
        });

        test('should have required methods', () => {
            // Проверяем основные методы
            const methods = Object.getOwnPropertyNames(Object.getPrototypeOf(instance));
            expect(methods.length).toBeGreaterThan(0);
        });

        test('should handle initialization', async () => {
            if (typeof instance.initialize === 'function') {
                await expect(instance.initialize()).resolves.not.toThrow();
            }
        });

        test('should handle errors gracefully', async () => {
            if (typeof instance.processTask === 'function') {
                // Тест с невалидными данными
                await expect(instance.processTask(null)).rejects.toThrow();
            }
        });
    });
`;
    }

    /**
     * Генерирует тест для функции
     */
    generateFunctionTest(funcName, isAsync) {
        const asyncKeyword = isAsync ? 'async ' : '';
        const awaitKeyword = isAsync ? 'await ' : '';
        const resolves = isAsync ? '.resolves' : '';

        return `
    describe('${funcName}', () => {
        test('should be defined', () => {
            expect(${funcName}).toBeDefined();
            expect(typeof ${funcName}).toBe('function');
        });

        test('should handle valid input', ${asyncKeyword}() => {
            ${isAsync ? `await expect(${funcName}({}))${resolves}.not.toThrow();` : 
                      `expect(() => ${funcName}({})).not.toThrow();`}
        });

        test('should handle invalid input', ${asyncKeyword}() => {
            ${isAsync ? `await expect(${funcName}(null)).rejects.toThrow();` :
                      `expect(() => ${funcName}(null)).toThrow();`}
        });
    });
`;
    }

    /**
     * Создает Jest конфигурацию
     */
    async generateJestConfig() {
        const config = {
            type: "module",
            testEnvironment: "node",
            testMatch: ["**/tests/**/*.test.js"],
            collectCoverage: true,
            coverageDirectory: "coverage",
            coverageReporters: ["text", "lcov", "html"],
            coverageThreshold: {
                global: {
                    branches: 70,
                    functions: 70,
                    lines: 70,
                    statements: 70
                }
            },
            setupFilesAfterEnv: ["<rootDir>/tests/setup.js"],
            testTimeout: 30000,
            verbose: true
        };

        await fs.writeFile(
            path.join(__dirname, 'jest.config.json'),
            JSON.stringify(config, null, 2)
        );

        console.log('✅ Jest конфигурация создана');
    }

    /**
     * Создает setup файл для тестов
     */
    async generateTestSetup() {
        const setupContent = `/**
 * Jest Setup для NASH 4.0 Digital Twin
 */

// Мокаем внешние сервисы
jest.mock('node:fs/promises');
jest.mock('sqlite3');

// Глобальные переменные для тестов
global.TEST_ENV = true;
global.MOCK_MODE = true;

// Увеличиваем таймаут для долгих операций
jest.setTimeout(30000);

// Подавляем логи в тестах
console.log = jest.fn();
console.info = jest.fn();
console.warn = jest.fn();

// Очистка после каждого теста
afterEach(() => {
    jest.clearAllMocks();
});

console.log('🧪 Test environment initialized');
`;

        await fs.writeFile(
            path.join(this.testsDir, 'setup.js'),
            setupContent
        );

        console.log('✅ Test setup создан');
    }

    /**
     * Обновляет package.json с тестовыми скриптами
     */
    async updatePackageJson() {
        try {
            const packagePath = path.join(__dirname, 'package.json');
            const packageContent = await fs.readFile(packagePath, 'utf-8');
            const packageData = JSON.parse(packageContent);

            // Добавляем Jest как dev dependency
            if (!packageData.devDependencies) {
                packageData.devDependencies = {};
            }

            packageData.devDependencies.jest = "^29.0.0";
            packageData.devDependencies["@jest/globals"] = "^29.0.0";

            // Добавляем скрипты
            if (!packageData.scripts) {
                packageData.scripts = {};
            }

            packageData.scripts.test = "jest";
            packageData.scripts["test:watch"] = "jest --watch";
            packageData.scripts["test:coverage"] = "jest --coverage";
            packageData.scripts["test:ci"] = "jest --ci --coverage --watchAll=false";

            await fs.writeFile(packagePath, JSON.stringify(packageData, null, 2));
            console.log('✅ package.json обновлен');
        } catch (error) {
            console.warn('⚠️ Не удалось обновить package.json:', error.message);
        }
    }

    /**
     * Создает отчет о mock функциях
     */
    async generateMockReport(modules) {
        const mockModules = modules.filter(m => m && m.hasMockFunctions);
        
        let report = `# Mock Functions Report\n\n`;
        report += `Дата: ${new Date().toISOString()}\n\n`;
        report += `## Найдено ${mockModules.length} модулей с mock функциями\n\n`;

        for (const module of mockModules) {
            report += `### ${module.relativePath}\n`;
            report += `- ⚠️ **КРИТИЧЕСКОЕ**: Содержит mock/demo функции в production коде\n`;
            report += `- **Рекомендация**: Вынести в отдельные test-only модули\n\n`;
        }

        report += `## Рекомендации\n\n`;
        report += `1. Создать отдельную папку \`src/mocks/\` для mock функций\n`;
        report += `2. Использовать environment variables для переключения между production и mock режимами\n`;
        report += `3. Добавить lint правила для предотвращения mock функций в production\n`;

        await fs.writeFile(path.join(__dirname, 'MOCK_FUNCTIONS_REPORT.md'), report);
        console.log('📊 Отчет о mock функциях создан');
    }

    /**
     * Главная функция генерации
     */
    async generate() {
        console.log('🚀 Запуск автоматической генерации тестов...\n');

        // Создаем папку для тестов
        await fs.mkdir(this.testsDir, { recursive: true });

        // Сканируем модули
        await this.scanModules();

        console.log('📝 Анализ модулей...');
        const analyzedModules = [];
        
        for (const modulePath of this.modules) {
            const analysis = await this.analyzeModule(modulePath);
            if (analysis) {
                analyzedModules.push(analysis);
            }
        }

        console.log(`✅ Проанализировано ${analyzedModules.length} модулей\n`);

        // Генерируем тесты
        console.log('🔧 Генерация тестов...');
        let testsGenerated = 0;

        for (const moduleInfo of analyzedModules) {
            const testContent = this.generateTest(moduleInfo);
            if (testContent) {
                const testFileName = path.basename(moduleInfo.relativePath, '.js') + '.test.js';
                const testFilePath = path.join(this.testsDir, testFileName);
                
                await fs.writeFile(testFilePath, testContent);
                testsGenerated++;
            }
        }

        console.log(`✅ Создано ${testsGenerated} тестовых файлов\n`);

        // Создаем Jest конфигурацию
        await this.generateJestConfig();
        await this.generateTestSetup();
        await this.updatePackageJson();

        // Генерируем отчет о mock функциях
        await this.generateMockReport(analyzedModules);

        console.log('🎉 Автоматическая генерация тестов завершена!');
        console.log('\n📋 Что делать дальше:');
        console.log('1. npm install - установить Jest');
        console.log('2. npm test - запустить тесты');
        console.log('3. npm run test:coverage - проверить покрытие');
        console.log('4. Проверить MOCK_FUNCTIONS_REPORT.md для исправления mock функций');
    }
}

// Запуск генератора
const generator = new TestGenerator();
generator.generate().catch(console.error);