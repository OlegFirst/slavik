class BcmIsoClause(models.Model):
    _name = 'bcm.iso.clause'
    _description = 'ISO 22301 Clause'

    name = fields.Char('Clause Number', required=True)
    title = fields.Char('Clause Title', required=True)
    description = fields.Text('Description')

    # ISO structure
    section = fields.Selection([
        ('4', 'Context of the organization'),
        ('5', 'Leadership'),
        ('6', 'Planning'),
        ('7', 'Support'),
        ('8', 'Operation'),
        ('9', 'Performance evaluation'),
        ('10', 'Improvement')
    ])

    # Computed fields
    article_count = fields.Integer('Article Count', compute='_compute_article_count')

    company_id = fields.Many2one('res.company', required=True, default=lambda self: self.env.company)

    def _compute_article_count(self):
        """Compute number of articles for this ISO clause"""
        for clause in self:
            clause.article_count = self.env['bcm.knowledge.article'].search_count([
                '|',
                ('iso_clause_id', '=', clause.id),
                ('iso_clauses', 'in', clause.id)
            ])


